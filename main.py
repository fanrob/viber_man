    logging.basicConfig(level=logging.INFO)
    logger = logging.getLogger(__name__)
    logger.info("Запуск основного цикла...")
    while True:
        # приводим окно к базовому состоянию
        viber.activate()
        viber.scroll_chats_to_up()
        viber.close_holiday()
        logger.info("Проверка новых сообщений...")
        if viber.has_new_messages():
            logger.info("Новые сообщения обнаружены.")
            lines = viber.get_chat_list()   #получаем список чатов на экране вместе с фиолетовыми кружками
         
            for line in lines:
                if line.has_new_message:
                    #проверяем, что имя чата корректно и узнаем точное имя чата
                    viber.open_chat(line.position)

                    cchat_name = viber.get_opened_chat_name()       #точное имя чата, которое будем писать в БД
                    logger.info(f"Найден чат с новым сообщением: {line.chat_name}")
                    logger.info(f"Открыт чат: {cchat_name}")
                    viber.scroll_messages_to_bottom()
                    #TODO: тут будет сначала получение даты-времени последнего сообщения из БД, а потом получение сообщений с момента последнего сообщения
                    new_messages = viber.get_messages(datetime.datetime.now() - datetime.timedelta(minutes=3600))    
                        
                    for message in new_messages:
                        logger.info(f"Новое сообщение: {message}")
