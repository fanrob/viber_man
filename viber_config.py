"""Константы для взаимодействия с окном Viber.

Все координаты подбираются с помощью MPos.exe (пиксель + цвет) и задаются
относительно окна Viber: (0, 0) — левый верхний угол окна.

    Zone  = (x, y, ширина, высота)   — прямоугольная зона
    Point = (x, y)                   — точка (для скролла колёсиком)
    RGB   = (R, G, B)                — цвет пикселя
"""

from typing import Tuple

Zone = Tuple[int, int, int, int]
Point = Tuple[int, int]
RGB = Tuple[int, int, int]

# ---------------------------------------------------------------------------
# Окно
# ---------------------------------------------------------------------------

WINDOW_TITLE = "Rakuten Viber"  # заголовок окна Viber (для поиска окна)

# ---------------------------------------------------------------------------
# Зоны экрана (относительно окна Viber)
# ---------------------------------------------------------------------------

# Зона с индикатором новых сообщений (например, синий бейдж у чата)
NEW_MESSAGES_ZONE: Zone = (0, 60, 40, 60)

# Список чатов (панель слева)
CHAT_LIST_ZONE: Zone = (0, 60, 320, 640)

# Лента сообщений (правая часть окна)
MESSAGES_ZONE: Zone = (320, 60, 680, 640)

# Поле ввода нового сообщения (снизу, правая часть окна)
MESSAGE_INPUT_ZONE: Zone = (330, 690, 640, 50)

# ---------------------------------------------------------------------------
# Цвета и пороги
# ---------------------------------------------------------------------------

# Цвет пикселей, наличие которых означает "есть новые сообщения"
NEW_MESSAGE_COLOR: RGB = (74, 168, 255)  # синий бейдж Viber (подобрать MPos)
NEW_MESSAGE_COLOR_TOLERANCE = 40         # допуск отклонения цвета (0..255)
NEW_MESSAGE_MIN_PIXELS = 5               # минимум совпадающих пикселей в зоне

# ---------------------------------------------------------------------------
# Скролл колёсиком (точки, над которыми вращается колёсико)
# ---------------------------------------------------------------------------

CHATS_SCROLL_POINT: Point = (160, 400)    # над списком чатов
MESSAGES_SCROLL_POINT: Point = (660, 400)  # над лентой сообщений

SCROLL_UP = 1     # прокрутить вверх
SCROLL_DOWN = -1  # прокрутить вниз
SCROLL_AMOUNT = 5  # "щелчки" колёсика за один вызов

# ---------------------------------------------------------------------------
# Задержки (секунды)
# ---------------------------------------------------------------------------

WINDOW_ACTIVATE_DELAY = 0.3   # после активации окна
CLICK_SETTLE_DELAY = 0.3      # после клика (фокус в поле ввода)
TYPE_INTERVAL = 0.02          # интервал между символами (запасной ввод)
SEND_KEY_DELAY = 0.1          # перед нажатием Enter
SCROLL_SETTLE_DELAY = 0.2     # после скролла (список перерисовался)
CHAT_OPEN_DELAY = 0.5         # после клика по чату (чат открылся)
